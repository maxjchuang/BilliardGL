import copy, importlib.util, json, pathlib, unittest
ROOT = pathlib.Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("v", ROOT / "scripts/validate_m4_d5_d_push_frozen_classification_policy_candidate_register.py")
V = importlib.util.module_from_spec(SPEC); SPEC.loader.exec_module(V)
BASE = json.loads(V.PATH.read_text())
class Tests(unittest.TestCase):
    def reject(self, fn):
        d = copy.deepcopy(BASE); fn(d)
        with self.assertRaises(Exception): V.validate(d)
    def test_valid(self): V.validate(copy.deepcopy(BASE))
    def test_schema(self): self.reject(lambda d: d.update(schema="bad"))
    def test_status(self): self.reject(lambda d: d.update(status="selected"))
    def test_binding(self): self.reject(lambda d: d["authority_bindings"]["d5_c_receipt"].update(sha256="0"*64))
    def test_count(self): self.reject(lambda d: d["selection_contract"].update(bundle_count=2))
    def test_order(self): self.reject(lambda d: d["bundles"][1].update(order=9))
    def test_id(self): self.reject(lambda d: d["bundles"][0].update(id="other"))
    def test_duplicate(self): self.reject(lambda d: d["selection_contract"]["stable_order"].__setitem__(1, d["selection_contract"]["stable_order"][0]))
    def test_selected(self): self.reject(lambda d: d["bundles"][0].update(selection_status="SELECTED"))
    def test_two_recommended(self): self.reject(lambda d: d["bundles"][1].update(recommended=True))
    def test_wrong_recommended(self): self.reject(lambda d: d["selection_contract"].update(recommended_id=d["bundles"][1]["id"]))
    def test_duration_threshold(self): self.reject(lambda d: d["bundles"][0]["duration_distance_policy"].update(duration_threshold_seconds=0.01))
    def test_distance_threshold(self): self.reject(lambda d: d["bundles"][0]["duration_distance_policy"].update(distance_threshold_cm=0.1))
    def test_tolerance(self): self.reject(lambda d: d["bundles"][0]["duration_distance_policy"].update(comparison_tolerance=1e-6))
    def test_machine_push(self): self.reject(lambda d: d["bundles"][0]["duration_distance_policy"].update(automatic_push_classification=True))
    def test_authority(self): self.reject(lambda d: d["bundles"][0].update(push_obviousness_authority="PLAYER"))
    def test_jaw(self): self.reject(lambda d: d["bundles"][0]["frozen_cushion_policy"].update(pocket_jaw_counts=True))
    def test_prerequisite(self): self.reject(lambda d: d["bundles"][0]["frozen_cushion_policy"].update(prerequisite_legal_cushion_predicate="ANY_RAIL"))
    def test_machine_ratio(self): self.reject(lambda d: d["bundles"][1]["duration_distance_policy"].update(duration_threshold_ratio=1.5))
    def test_machine_calibration(self): self.reject(lambda d: d["bundles"][1]["duration_distance_policy"].update(calibration_manifest_required_before_implementation=False))
    def test_jaw_alternative(self): self.reject(lambda d: d["bundles"][2]["frozen_cushion_policy"].update(pocket_jaw_counts=False))
    def test_root_gate(self): self.reject(lambda d: d["selection_contract"].update(root_selection_required_before_implementation_gate=False))
    def test_allowlist(self): self.reject(lambda d: d["future_implementation_allowlist"].update(dormant_until_root_selection_and_implementation_gate=False))
    def test_fixture(self): self.reject(lambda d: d["future_fixtures"]["negative"].pop())
    def test_false_implementation(self): self.reject(lambda d: d["claims"].update(implementation_authorized=True))
    def test_false_d5_complete(self): self.reject(lambda d: d["claims"].update(d5_complete=True))
    def test_false_m4_complete(self): self.reject(lambda d: d["claims"].update(m4_complete=True))
if __name__ == "__main__": unittest.main()
