import copy,importlib.util,json,pathlib,unittest
R=pathlib.Path(__file__).resolve().parents[2];S=importlib.util.spec_from_file_location('v',R/'scripts/validate_m4_d5_stage_completion_and_audit_v10.py');V=importlib.util.module_from_spec(S);S.loader.exec_module(V)
SB=json.loads(V.STAGE.read_text());AB=json.loads(V.AUDIT.read_text())
class Tests(unittest.TestCase):
 def rs(self,fn):
  d=copy.deepcopy(SB);fn(d)
  with self.assertRaises(Exception):V.validate_stage(d,False)
 def ra(self,fn):
  d=copy.deepcopy(AB);fn(d)
  with self.assertRaises(Exception):V.validate_audit(d,False)
 def test_live(self):V.validate_stage(copy.deepcopy(SB),True);V.validate_audit(copy.deepcopy(AB),True)
 def test_stage_schema(self):self.rs(lambda d:d.update(schema='bad'))
 def test_stage_status(self):self.rs(lambda d:d.update(status='NONFINAL'))
 def test_batch_order(self):self.rs(lambda d:d['stage_batches'].reverse())
 def test_batch_state(self):self.rs(lambda d:d['stage_batches'][0].update(state='MISSING'))
 def test_stage_rows(self):self.rs(lambda d:d['row_assessments'].pop())
 def test_stage_false_promotion(self):self.rs(lambda d:d['row_assessments'][4].update(successor_recommendation='IMPLEMENTED'))
 def test_stage_d6(self):self.rs(lambda d:d['dependency_successor'].update(D6_OFF_TABLE_PHYSICS='SATISFIED'))
 def test_stage_m4(self):self.rs(lambda d:d['claims'].update(m4_complete=True))
 def test_audit_schema(self):self.ra(lambda d:d.update(schema_version=11))
 def test_audit_status(self):self.ra(lambda d:d.update(audit_status='NONFINAL'))
 def test_summary(self):self.ra(lambda d:d['summary'].update(implemented=20))
 def test_row_count(self):self.ra(lambda d:d['matrix'].pop())
 def test_unrelated_row(self):self.ra(lambda d:next(x for x in d['matrix'] if x['id']=='WPA-II-21').update(assessment='drift'))
 def test_12_5_6(self):self.ra(lambda d:next(x for x in d['matrix'] if x['id']=='WPA-II-12-5-6').update(status='PARTIAL'))
 def test_12_7(self):self.ra(lambda d:next(x for x in d['matrix'] if x['id']=='WPA-II-12-7').update(product_reachable=False))
 def test_15_1(self):self.ra(lambda d:next(x for x in d['matrix'] if x['id']=='WPA-II-15-1')['gaps'].append('gap'))
 def test_15_2(self):self.ra(lambda d:next(x for x in d['matrix'] if x['id']=='WPA-II-15-2').update(status='MISSING'))
 def test_17(self):self.ra(lambda d:next(x for x in d['matrix'] if x['id']=='WPA-II-17').update(status='IMPLEMENTED'))
 def test_m4_list(self):self.ra(lambda d:d['m4_required_unclosed'].remove('WPA-II-17'))
 def test_d6_boundary(self):self.ra(lambda d:d['d5_completion_boundaries'].update(d6_off_table_complete=True))
 def test_profile(self):self.ra(lambda d:d.update(profile_complete=True))
 def test_product(self):self.ra(lambda d:d.update(product_exposed=True))
 def test_gpu(self):self.ra(lambda d:d['d5_completion_boundaries'].update(gpu_executed=True))
if __name__=='__main__':unittest.main()
