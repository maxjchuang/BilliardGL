import copy, importlib.util, json, pathlib, unittest
ROOT=pathlib.Path(__file__).resolve().parents[1]
SPEC=importlib.util.spec_from_file_location('v',ROOT/'scripts/validate_m4_d5_d_push_frozen_classification_implementation.py')
V=importlib.util.module_from_spec(SPEC); SPEC.loader.exec_module(V)
BASE=json.loads(V.RECEIPT.read_text())
class Tests(unittest.TestCase):
    def reject(self,fn):
        d=copy.deepcopy(BASE); fn(d)
        with self.assertRaises(Exception): V.validate(d)
    def test_valid(self): V.validate(copy.deepcopy(BASE))
    def test_schema(self): self.reject(lambda d:d.update(schema='bad'))
    def test_status(self): self.reject(lambda d:d.update(status='complete'))
    def test_policy_sha(self): self.reject(lambda d:d['authority_bindings']['root_selected_policy'].update(sha256='0'*64))
    def test_gate_sha(self): self.reject(lambda d:d['authority_bindings']['implementation_design_gate'].update(sha256='0'*64))
    def test_bundle(self): self.reject(lambda d:d['authority_bindings']['root_selected_policy'].update(bundle='D5D-B'))
    def test_red(self): self.reject(lambda d:d['tests_first'].update(red_observed=False))
    def test_green(self): self.reject(lambda d:d['tests_first'].update(green=False))
    def test_duration_threshold(self): self.reject(lambda d:d['contract'].update(duration_threshold_seconds=0.1))
    def test_distance_threshold(self): self.reject(lambda d:d['contract'].update(distance_threshold_cm=1.0))
    def test_tolerance(self): self.reject(lambda d:d['contract'].update(comparison_tolerance=1e-6))
    def test_signed(self): self.reject(lambda d:d['contract'].update(signed_same_shot_referee_final_required=False))
    def test_jaw(self): self.reject(lambda d:d['contract'].update(jaw_counts=True))
    def test_fixture(self): self.reject(lambda d:d['fixtures']['negative'].pop())
    def test_prod(self): self.reject(lambda d:d['source_bindings'].pop())
    def test_tests(self): self.reject(lambda d:d['test_bindings'].pop())
    def test_source_sha(self): self.reject(lambda d:d['source_bindings'][0].update(sha256='0'*64))
    def test_test_sha(self): self.reject(lambda d:d['test_bindings'][0].update(sha256='0'*64))
    def test_cmake_sha(self): self.reject(lambda d:d['build_binding'].update(sha256='0'*64))
    def test_cpu(self): self.reject(lambda d:d['cpu'].update(passed_count=10))
    def test_binary(self): self.reject(lambda d:d['cpu']['binaries'][0].update(sha256='0'*64))
    def test_gpu(self): self.reject(lambda d:d['cpu'].update(gpu=True))
    def test_false_d5(self): self.reject(lambda d:d['completion'].update(d5_complete=True))
    def test_false_audit(self): self.reject(lambda d:d['completion'].update(audit_rows_changed=True))
    def test_false_m4(self): self.reject(lambda d:d['completion'].update(m4_complete=True))
if __name__=='__main__': unittest.main()
